"""Read-only audit plus isolated recovery probes. Never writes to production Git."""
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
REPO = HERE.parent / 'build-audit/zdoc'
DEV = '96d7a73cc0ae9f3882269000eae2ac750e418386'
NODE = '/Users/liyun/.nvm/versions/node/v24.18.0/bin/node'


def run(args, cwd=REPO):
    try:
        return subprocess.check_output(args, cwd=cwd, text=True, stderr=subprocess.PIPE)
    except subprocess.CalledProcessError as error:
        raise RuntimeError(error.stderr) from error


def git(*args, cwd=REPO):
    return run(['git', *args], cwd).strip()


paths = git('ls-tree', '-r', '--name-only', DEV).splitlines()
prefixes = ['content/en/', 'i18n/ja-JP/', '.translation-cache/', 'generated/en/',
            'packages/docs-tooling/src/lark/meta/assembly/',
            'packages/docs-tooling/src/lark/meta/snapshots/']
pages = [p for p in paths if p.endswith('/openai.md') and
         p.startswith(('content/en/', 'i18n/ja-JP/'))]
source_files = ['deploy/contracts/README.md', 'deploy/contracts/verify-image.mjs',
                'deploy/en/Dockerfile', 'scripts/restore-generated-state.sh',
                'scripts/docs-workflow/guides-media-prefetch.js',
                'packages/docs-tooling/src/lark/larkImageDownloader.js']
report = {
    'scope': 'Git objects and synthetic local probes; no deployment or full site build',
    'dev_sha': DEV,
    'tooling_sha': git('rev-parse', 'HEAD'),
    'node': run([NODE, '--version']).strip(),
    'tracked_counts': {p: sum(f.startswith(p) for f in paths) for p in prefixes},
    'openai_blobs': [],
    'master_dev_same_blob': {p: git('rev-parse', 'HEAD:' + p) == git('rev-parse', DEV + ':' + p)
                             for p in source_files},
}
for p in pages:
    data = subprocess.check_output(['git', 'show', DEV + ':' + p], cwd=REPO)
    report['openai_blobs'].append({'path': p, 'bytes': len(data),
                                   'sha256': hashlib.sha256(data).hexdigest()})

with tempfile.TemporaryDirectory(prefix='zdoc-recovery-audit-') as temp:
    root = Path(temp)
    git('init', '-q', cwd=root)
    git('config', 'user.name', 'Recovery audit fixture', cwd=root)
    git('config', 'user.email', 'fixture@example.invalid', cwd=root)
    originals = {
        'content/en/guides/openai.md': 'Original English\n',
        'i18n/ja-JP/openai.md': 'Original Japanese\n',
        'generated/en/sidebars/guides.sidebar.js': 'module.exports = ["openai"]\n',
        '.translation-cache/test.json': '{"version":1}\n',
    }
    for p, value in originals.items():
        dest = root / p
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(value)
    git('add', '.', cwd=root)
    git('commit', '-qm', 'fixture baseline', cwd=root)
    baseline = git('rev-parse', 'HEAD', cwd=root)
    for p in originals:
        (root / p).write_text('New generated bytes\n')
    extra = root / 'content/en/guides/new-only.md'
    extra.write_text('New page\n')
    git('add', '.', cwd=root)
    git('commit', '-qm', 'fixture candidate', cwd=root)
    # No remote is configured. Every needed old byte must come from local Git.
    run(['bash', str(REPO / 'scripts/restore-generated-state.sh'), '--exact', '--ref', baseline], root)
    checks = {p: (root / p).read_text() == value for p, value in originals.items()}
    checks['new_only_page_removed'] = not extra.exists()
    assert all(checks.values()), checks
    report['isolated_git_restore'] = {'passed': len(checks), 'checks': checks,
                                       'remote_configured': False, 'ci_artifact_used': False}

node_probe = r'''
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const root = process.argv[1];
const {verifyRollbackTarget} = await import(pathToFileURL(root + '/deploy/contracts/verify-image.mjs'));
const digest = 'sha256:' + 'a'.repeat(64);
const record = {site:'en', environment:'prod', mode:'specified-image', sourceRepository:'zdoc',
 sourceSha:'1'.repeat(40), finalDeployedDigest:digest, sourceUatDigest:'sha256:'+'b'.repeat(64),
 operatorImageRef:'registry.example.invalid/docs@'+digest,
 jenkinsBuildIdentity:'vdc-jenkins/english-prod/1', status:'succeeded'};
const provider = records => ({getAuthenticatedUatRecords:async()=>[], resolveImageReference:async()=>digest,
 getSuccessfulProdRecords:async()=>records});
const request = {site:'en', targetDigest:digest};
assert.equal(await verifyRollbackTarget(request, provider([record])), digest);
await assert.rejects(verifyRollbackTarget(request, provider([])), /recorded successful/);
await assert.rejects(verifyRollbackTarget(request, provider([{...record,status:'failed'}])), /recorded successful/);
await assert.rejects(verifyRollbackTarget({...request,site:'zh-CN'}, provider([record])), /recorded successful/);
console.log(JSON.stringify({passed:4, scope:'pure rollback verifier with synthetic trusted provider; no registry access'}));
'''
report['rollback_verifier'] = json.loads(run([NODE, '--input-type=module', '-e', node_probe, str(REPO)]))
output = HERE / 'probe-results.json'
output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n')
print(json.dumps(report, ensure_ascii=False, indent=2))
